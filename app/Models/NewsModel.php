<?php

namespace App\Models;

use CodeIgniter\Model;
use Config\Database;

class NewsModel extends Model
{
    protected $table = 'news_posts';
    protected $primaryKey = 'id';
    protected $returnType = 'array';
    protected $allowedFields = [
        'title',
        'content',
        'link_url',
        'image_path',
        'author_name',
        'author_role',
    ];
    protected $useTimestamps = false;

    public function __construct()
    {
        parent::__construct();
        $this->ensureTable();
    }

    public function getAllPublished(): array
    {
        return $this->select([
                'id',
                'title',
                'content',
                'link_url',
                'image_path',
                'author_name',
                'author_role',
                'created_at',
            ])
            ->orderBy('created_at', 'DESC')
            ->findAll();
    }

    private function ensureTable(): void
    {
        $db = Database::connect();
        $tableName = $db->prefixTable($this->table);

        if ($db->tableExists($this->table)) {
            $fields = $db->getFieldNames($this->table);
            if (! in_array('link_url', $fields, true)) {
                $db->query("ALTER TABLE {$tableName} ADD COLUMN IF NOT EXISTS link_url text DEFAULT NULL");
            }
            return;
        }

        $sql = "CREATE TABLE IF NOT EXISTS {$tableName} (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title text NOT NULL,
            content text NOT NULL,
            link_url text DEFAULT NULL,
            image_path text DEFAULT NULL,
            author_name text NOT NULL,
            author_role text DEFAULT NULL,
            created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
        )";

        $db->query($sql);
    }
}
