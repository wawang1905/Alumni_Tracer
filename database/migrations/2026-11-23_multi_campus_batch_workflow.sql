-- 1. Add Campus_ID to alumni_batches so each campus can independently own
--    the same GraduationYear without overwriting another campus's batch.
ALTER TABLE public.alumni_batches
    ADD COLUMN IF NOT EXISTS "Campus_ID" bigint NULL;

-- Drop any legacy global UNIQUE constraint on GraduationYear only (if present)
DO $$
DECLARE
    con_name text;
BEGIN
    SELECT c.conname INTO con_name
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = 'public'
      AND t.relname = 'alumni_batches'
      AND c.contype = 'u'
      AND pg_get_constraintdef(c.oid) ILIKE '%("GraduationYear")%'
      AND pg_get_constraintdef(c.oid) NOT ILIKE '%Campus_ID%';

    IF con_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE public.alumni_batches DROP CONSTRAINT %I', con_name);
    END IF;
END $$;

-- Enforce uniqueness per (Campus_ID, GraduationYear) for campus-scoped batches
CREATE UNIQUE INDEX IF NOT EXISTS idx_alumni_batches_campus_year
    ON public.alumni_batches ("Campus_ID", "GraduationYear")
    WHERE "Campus_ID" IS NOT NULL;

-- Preserve uniqueness for legacy rows where Campus_ID is NULL
CREATE UNIQUE INDEX IF NOT EXISTS idx_alumni_batches_legacy_year
    ON public.alumni_batches ("GraduationYear")
    WHERE "Campus_ID" IS NULL;

-- 2. Create alumni_batch_colleges so a College can be associated with a Batch
--    even before any Departments have been added or imported under it.
CREATE TABLE IF NOT EXISTS public.alumni_batch_colleges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Campus_ID" bigint NOT NULL,
    "GraduationYear" integer NOT NULL,
    "College_ID" bigint NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_batch_campus_college UNIQUE ("Campus_ID", "GraduationYear", "College_ID")
);

CREATE INDEX IF NOT EXISTS idx_alumni_batch_colleges_lookup
    ON public.alumni_batch_colleges ("Campus_ID", "GraduationYear");

-- Backfill alumni_batch_colleges from existing alumni_batch_departments (non-destructive)
INSERT INTO public.alumni_batch_colleges ("Campus_ID", "GraduationYear", "College_ID")
SELECT DISTINCT c."Campus_ID", abd."GraduationYear", abd."College_ID"
FROM public.alumni_batch_departments abd
JOIN public.colleges c ON c."College_ID" = abd."College_ID"
WHERE c."Campus_ID" IS NOT NULL
ON CONFLICT ("Campus_ID", "GraduationYear", "College_ID") DO NOTHING;
