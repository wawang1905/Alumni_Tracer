-- Payments table schema for Alumni Tracer
CREATE TABLE IF NOT EXISTS `payments` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `transaction_ref` VARCHAR(64) NOT NULL UNIQUE,
  `alumni_id` INT(11) NULL,
  `student_number` VARCHAR(50) NULL,
  `payer_name` VARCHAR(255) NOT NULL,
  `payer_email` VARCHAR(255) NULL,
  `payer_contact` VARCHAR(50) NULL,
  `campus_id` INT(11) NULL,
  `college_id` INT(11) NULL,
  `payment_type` ENUM('alumni_id', 'event_fee', 'membership', 'graduation_fee', 'donation', 'document_cert', 'other') NOT NULL DEFAULT 'alumni_id',
  `description` VARCHAR(255) NULL,
  `amount` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `payment_method` ENUM('cash', 'gcash', 'maya', 'bank_transfer', 'online_portal', 'over_the_counter') NOT NULL DEFAULT 'cash',
  `channel_reference` VARCHAR(100) NULL,
  `status` ENUM('pending', 'verified', 'rejected', 'refunded') NOT NULL DEFAULT 'pending',
  `proof_file` VARCHAR(255) NULL,
  `submitted_by_role` VARCHAR(50) NULL DEFAULT 'alumni',
  `coordinator_id` INT(11) NULL,
  `notes` TEXT NULL,
  `verified_by` INT(11) NULL,
  `verified_at` DATETIME NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_status` (`status`),
  INDEX `idx_payment_type` (`payment_type`),
  INDEX `idx_college_id` (`college_id`),
  INDEX `idx_campus_id` (`campus_id`),
  INDEX `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
